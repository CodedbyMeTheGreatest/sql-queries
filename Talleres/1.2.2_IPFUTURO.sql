SELECT * FROM ALUMNO;

SELECT CARRERAID "INDENTIFICACION DE LA CARRERA",
COUNT(ALUMNOID) "TOTAL ALUMNOS MATRICULADOS",
'Le corresponden '||TO_CHAR(30200 * COUNT(ALUMNOID), '$999G999')||' del presupuesto asignado para publicidad.' "MONTO POR PUBLICIDAD"
FROM ALUMNO
GROUP BY CARRERAID
ORDER BY "TOTAL ALUMNOS MATRICULADOS" DESC;

