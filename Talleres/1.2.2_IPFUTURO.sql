SELECT * FROM PRESTAMO;

SELECT TITULOID "CODIGO DEL LIBRO",
COUNT(RUN_EMP) "TOTAL DE VECES SOLICITADO",
CASE
WHEN COUNT(RUN_EMP) = 1 THEN 'No se requiere comprar nuevos ejemplares'
WHEN COUNT(RUN_EMP) BETWEEN 2 AND 3 THEN 'Se requiere comprar 1 nuevo ejemplar'
WHEN COUNT(RUN_EMP) BETWEEN 4 AND 5 THEN 'Se requiere comprar 2 nuevos ejemplares'
ELSE 'Se requiere comprar 4 nuevos ejemplares'
END "           SUGERENCIA"
FROM PRESTAMO
WHERE EXTRACT(YEAR FROM FECHA_INI_PRESTAMO) = EXTRACT(YEAR FROM SYSDATE) - 1
GROUP BY TITULOID
ORDER BY "TOTAL DE VECES SOLICITADO" DESC;

