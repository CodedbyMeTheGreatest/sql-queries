SELECT * FROM PRESTAMO;

SELECT TO_CHAR(RUN_EMP, '99G999G999') "RUN EMPLEADO",
TO_CHAR(FECHA_INI_PRESTAMO, 'MM/YYYY') "MES PRESTAMOS LIBROS",
COUNT(PRESTAMOID) "TOTAL PRESTAMOS ATENDIDOS",
TO_CHAR(COUNT(PRESTAMOID)*10000, '$99,999') "ASIGNACION POR PRESTAMOS"
FROM PRESTAMO
WHERE EXTRACT(YEAR FROM FECHA_INI_PRESTAMO) = EXTRACT(YEAR FROM SYSDATE) - 1
GROUP BY RUN_EMP, TO_CHAR(FECHA_INI_PRESTAMO, 'MM/YYYY')
HAVING COUNT(PRESTAMOID) > 2
ORDER BY "MES PRESTAMOS LIBROS", "ASIGNACION POR PRESTAMOS" DESC, "RUN EMPLEADO" DESC;


