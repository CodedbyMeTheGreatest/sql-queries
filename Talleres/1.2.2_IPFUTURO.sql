SELECT * FROM EMPLEADO;

SELECT TO_CHAR(RUN_JEFE, '99G999G999') "RUN JEFE SIN DV",
COUNT(RUN_EMP) "TOTAL DE EMPLEADOS A SU CARGO", 
TO_CHAR(MAX(SALARIO), '99G999G999') "SALARIO MAXIMO",
(COUNT(RUN_EMP) * 10)||'% del Salario Máximo' "PORCENTAJE DE BONIFICACION",
TO_CHAR(MAX(SALARIO) * (COUNT(RUN_EMP)/100), '$999G999') "BONIFICACION"
FROM EMPLEADO
WHERE RUN_JEFE IS NOT NULL
GROUP BY RUN_JEFE
ORDER BY "TOTAL DE EMPLEADOS A SU CARGO";

