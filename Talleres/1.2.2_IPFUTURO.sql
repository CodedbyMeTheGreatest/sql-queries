SELECT * FROM ESCOLARIDAD_EMP;
SELECT * FROM EMPLEADO;

SELECT ID_ESCOLARIDAD "ESCOLARIDAD",
CASE ID_ESCOLARIDAD
WHEN 20 THEN 'MEDIA CIENTÍFICA HUMANISTA'
WHEN 30 THEN 'MEDIA TÉCNICO PROFESIONAL'
WHEN 40 THEN 'SUPERIOR CENTRO DE FORMACIÓN TÉCNICA'
WHEN 50 THEN 'SUPERIOR INSTITUTO PROFESIONAL'
WHEN 60 THEN 'SUPERIOR UNIVERSIDAD'
ELSE 'BÁSICA' 
END "DESCRIPCIÓN ESCOLARIDAD",
COUNT(RUN_EMP) "TOTAL DE EMPLEADOS",
TO_CHAR(ROUND(MAX(SALARIO)), '$9G999G999') "SALARIO MAXIMO",
TO_CHAR(ROUND(MIN(SALARIO)), '$9G999G999') "SALARIO MINIMO",
TO_CHAR(ROUND(SUM(SALARIO)), '$9G999G999') "SALARIO TOTAL",
TO_CHAR(ROUND(AVG(SALARIO)), '$9G999G999') "SALARIO PROMEDIO"
FROM EMPLEADO
GROUP BY ID_ESCOLARIDAD
ORDER BY "TOTAL DE EMPLEADOS" DESC;

